import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { parseResume, type Resume } from '../src/lib/resume-parse.ts';
import { reactionKeys } from '../src/lib/reactions.ts';
import { expand, leakedNameParts, replacements, tokenise } from '../src/lib/twin-privacy.ts';

const file = (path: string) => new URL(`../${path}`, import.meta.url);

function citeLabel(resume: Resume, id: string) {
  const exp = resume.experience.find((e) => e.id === id);
  if (exp) return `${exp.role} @ ${exp.company}`;
  const proj = resume.projects.find((p) => p.id === id);
  if (proj) return proj.name;
  return resume.writing.find((p) => p.id === id)?.title ?? id;
}

try {
  // src/content/ holds only generated files and is absent in a fresh clone.
  mkdirSync(file('src/content/'), { recursive: true });
  const resume = parseResume(readFileSync(file('ai/resume.template.md'), 'utf8'));
  writeFileSync(file('src/content/resume.json'), JSON.stringify(resume, null, 2) + '\n');

  // The reactions API imports only these keys, so no résumé content ends up in its bundle.
  const keys = reactionKeys(resume.writing.map((p) => p.id));
  writeFileSync(file('src/content/reaction-keys.ts'), `// Generated by scripts/build-resume.ts\nexport const REACTION_KEYS: readonly string[] = ${JSON.stringify(keys)};\n`);

  // ---- AI twin: tokenised résumé + system prompt for the server, placeholder values for the browser ----
  const pairs = replacements(resume.identity);
  const twin = JSON.parse(tokenise(JSON.stringify(resume), pairs)) as Resume;
  const twinJson = JSON.stringify(twin, null, 2);
  writeFileSync(file('src/content/resume.twin.json'), twinJson + '\n');

  const template = readFileSync(file('ai/twin-system-prompt.md'), 'utf8').split(/^---$/m).slice(1).join('---').trim();
  const system = template.replace('{{RESUME_JSON}}', JSON.stringify(twin));
  const leaks = leakedNameParts(system, resume.identity);
  if (leaks.length) throw new Error(`Name privacy: the twin system prompt still contains ${leaks.join(', ')}`);
  const citeIds = [...resume.experience, ...resume.projects, ...resume.writing].map((i) => i.id);
  const hash = createHash('sha256').update(system).digest('hex').slice(0, 16);
  writeFileSync(
    file('src/content/twin-prompt.ts'),
    `// Generated by scripts/build-resume.ts — tokenised, contains no part of the owner's name.\n` +
      `export const SYSTEM_PROMPT = ${JSON.stringify(system)};\n` +
      `export const RESUME_HASH = ${JSON.stringify(hash)};\n` +
      `export const CITE_IDS: readonly string[] = ${JSON.stringify(citeIds)};\n`,
  );

  const { identity } = resume;
  const values = {
    NAME: identity.name,
    NICKNAME: identity.nickname,
    EMAIL: identity.email,
    LINKEDIN: identity.linkedin,
    INSTAGRAM: identity.instagram,
    RESUME_PDF: identity.resume_pdf,
  };
  const client = {
    values,
    pairs,
    firstName: identity.name.split(' ')[0],
    cites: Object.fromEntries(citeIds.map((id) => [id, citeLabel(resume, id)])),
    faq: resume.faq.map((f) => ({ q: f.q, a: expand(f.a, values) })),
  };
  writeFileSync(file('src/content/twin-client.json'), JSON.stringify(client, null, 2) + '\n');

  // Career Coach's static instructions (everything after the first ---), cached by the API. No owner data in it.
  const career = readFileSync(file('ai/career-system-prompt.md'), 'utf8').split(/^---$/m).slice(1).join('---').trim();
  writeFileSync(file('src/content/career-prompt.ts'), `// Generated by scripts/build-resume.ts from ai/career-system-prompt.md\nexport const CAREER_PROMPT = ${JSON.stringify(career)};\n`);

  // /career renders per request, so whatever it imports ships in the server function: give it the display name only.
  writeFileSync(file('src/content/owner.json'), JSON.stringify({ name: identity.name, firstName: identity.name.split(' ')[0] }, null, 2) + '\n');

  console.log(`résumé → resume.json, resume.twin.json, twin-prompt.ts (${Math.round(system.length / 4)} est. tokens, hash ${hash})`);
} catch (err) {
  console.error('Résumé build failed:\n', err instanceof Error ? err.message : err);
  process.exit(1);
}
